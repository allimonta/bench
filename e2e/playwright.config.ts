import { defineConfig, devices } from '@playwright/test';
import { defineBddConfig, cucumberReporter } from 'playwright-bdd';
import 'dotenv/config';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const isCI = !!process.env.CI;
const baseURL = process.env.BASE_URL || 'http://localhost:4180';
const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const startsLocalApp = /^https?:\/\/(localhost|127\.0\.0\.1)(:\d+)?(\/|$)/.test(baseURL);

// Layout: src/main = framework code (pages, fixtures/DI, support, data, utils, reporters);
//         src/test = what is tested (steps, setup, resources/features).
// features (Gherkin) → steps (TS) → pages. bddgen turns each scenario into a Playwright test in .features-gen/.
const testDir = defineBddConfig({
  features: 'src/test/resources/features/**/*.feature',
  steps: ['src/test/steps/**/*.ts', 'src/test/hooks/**/*.ts', 'src/main/fixtures/**/*.ts'],
  outputDir: '.features-gen',
});

export default defineConfig({
  testDir,
  // Every scenario runs in parallel, with its own browser context and its own fixtures (DI per scenario). A clean-before
  // deletes only leftovers older than an hour (ScenarioContext.leftovers), never what another scenario has just created.
  fullyParallel: true,
  forbidOnly: isCI,
  retries: isCI ? 1 : 0,
  // 2 workers, as in CI: on a loaded machine one browser per CPU made context teardown (video/trace) exceed the test
  // timeout in passing scenarios (stabilize iterations 1-2: "Tearing down \"context\" exceeded the test timeout").
  workers: 2,
  timeout: 30_000,
  expect: { timeout: 7_000 },
  reporter: [
    ['list'],
    ['html', { open: 'never' }],
    ['json', { outputFile: 'test-results/results.json' }],
    ['junit', { outputFile: 'test-results/junit.xml' }],
    cucumberReporter('html', { outputFile: 'cucumber-report/index.html' }),
    ['./src/main/reporters/summary-reporter.ts'],
  ],
  use: {
    baseURL,
    testIdAttribute: process.env.TEST_ID_ATTRIBUTE || 'data-testid',
    trace: 'retain-on-failure',
    screenshot: 'only-on-failure',
    video: 'retain-on-failure',
    locale: 'en-US',
    // An action on a control that never appears fails with the locator it waited for, not with a bare test timeout.
    actionTimeout: 10_000,
    navigationTimeout: 15_000,
  },
  projects: [
    { name: 'setup', testDir: './src/test/setup', testMatch: /.*\.setup\.ts/ },
    {
      name: 'chromium',
      use: { ...devices['Desktop Chrome'], storageState: '.auth/user.json' },
      dependencies: ['setup'],
    },
  ],
  // Generated by QACluster (codegen-base.mjs) from the config start commands: each stays in the foreground.
  // An app that is already running is reused; nothing starts when BASE_URL points to a deployed app.
  webServer: startsLocalApp
    ? [
        {
          name: 'app',
          command: 'python3 -m http.server 4180 --bind 127.0.0.1',
          cwd: appRoot,
          url: baseURL,
          reuseExistingServer: true,
          timeout: 180_000,
          stdout: 'ignore',
          stderr: 'pipe',
          gracefulShutdown: { signal: 'SIGTERM', timeout: 30_000 },
        },
      ]
    : undefined,
});
