import type { FullConfig, FullResult, Reporter, Suite, TestCase, TestResult } from '@playwright/test/reporter';
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const clean = (m?: string) => m?.replace(/\x1b\[[0-9;]*m/g, '').split('\n')[0]?.slice(0, 200);

/** The case id and the title of a scenario's row. playwright-bdd names an Outline's examples "Example #1", "Example #2"
 *  inside a describe with the Outline's title; before, every example was a row of a case "Example" (testing v0.24.0,
 *  part 3). The id is, in order: the first word of the title when it is a case id (every plain scenario, as before); the
 *  first word of the nearest describe (an Outline with its id in the name); the scenario's own @TC- tag — the last one,
 *  the Feature's and the Rule's come first; else the first word of the title. An example's title is its Outline's name
 *  (without the id) and "Example #N". Known limit: two @TC- tags on one scenario and the second in its title → the title's. */
const CASE_ID = /^TC-[A-Za-z0-9_]+(?:-[A-Za-z0-9_]+)*$/;
type Titled = Pick<TestCase, 'title' | 'tags'> & { titlePath?: () => string[] };
function caseOf(test: Titled): { id: string; title: string } {
  const [first, ...rest] = test.title.split(' ');
  if (CASE_ID.test(first)) return { id: first, title: rest.join(' ') };
  const describe = (test.titlePath?.() ?? []).at(-2) ?? '';
  const [outlineFirst, ...outlineRest] = describe.split(' ');
  if (CASE_ID.test(outlineFirst)) return { id: outlineFirst, title: [outlineRest.join(' '), test.title].filter(Boolean).join(' — ') };
  const tagged = test.tags.filter((t) => /^@TC-/.test(t)).at(-1)?.slice(1);
  if (tagged) return { id: tagged, title: /^Example #\d+$/.test(test.title) ? [describe, test.title].filter(Boolean).join(' — ') : test.title };
  return { id: first, title: rest.join(' ') };
}

// Known bugs registry written by QACluster: { "BUG-001": { "signature": "text or /regex/ the failure must contain", "title": "…",
//   "stage": "precondition" | "action" | "assertion", "suspected": true? } }.
// A `@fail @BUG-NNN` scenario that fails with a DIFFERENT error is not the known bug: it is reported as a new failure.
// Any failure that matches a bug NOT tagged on that scenario (typically a suspected or intermittent bug in a precondition:
// the case never reached what it verifies) stays a failure, but the summary names the bug and where it hit.
type KnownBug = { signature?: string; title?: string; stage?: 'precondition' | 'action' | 'assertion'; suspected?: boolean };
const loadKnownBugs = (): Record<string, KnownBug> => {
  try { return existsSync('.qa-cluster/known-bugs.json') ? JSON.parse(readFileSync('.qa-cluster/known-bugs.json', 'utf8')) : {}; }
  catch { return {}; }
};
// Cases QACluster could not validate (run H): { "TC-…": { "platforms": { "web": { "reason": "…" } } } }. Their scenario is
// tagged @inconclusive: it runs; failing it is `known-inconclusive` with its reason (red), passing `inconclusive-passed`.
type Inconclusive = Record<string, { platforms?: Record<string, { reason?: string }> }>;
const loadInconclusive = (): Inconclusive => {
  try { return existsSync('.qa-cluster/inconclusive.json') ? JSON.parse(readFileSync('.qa-cluster/inconclusive.json', 'utf8')) : {}; }
  catch { return {}; }
};
const matches = (sig: string, text: string) => {
  const re = sig.match(/^\/(.*)\/([a-z]*)$/);
  return re ? new RegExp(re[1], re[2]).test(text) : text.includes(sig);
};

type Row = { id: string; title: string; file: string; outcome: string; duration: number; bug?: string; error?: string; testgraph?: string;
  knownMatch?: string; reason?: string };

/**
 * Per-run summary (generated by QACluster, runs without it).
 * Writes test-results/summary.md and summary.json and, in GitHub Actions, the job summary.
 * States: passed · failed · flaky · skipped · known-bug (scenario tagged @fail @BUG-NNN) · bug-fixed? (a known-bug that passed:
 *   green — a test that passes is fine in that run, whatever it did before; the summary says the bug is fixed and its tags can go)
 *   · known-bug-other-error (a known-bug scenario that failed with an error that is not the bug's signature: a new failure)
 *   · known-intermittent (tagged @intermittent @BUG-NNN, skipped in the normal run) · intermittent-fail / intermittent-pass
 *   (with RUN_INTERMITTENT=1: they run and the failure rate per bug is reported; they never turn the suite red)
 *   · known-inconclusive (tagged @inconclusive: a case QACluster could not validate, failing with its reason — red)
 *   · inconclusive-passed (it passed: green, the tag can be removed).
 */
/** A known bug's outcomes: on a scenario also tagged @inconclusive, @fail wins and the inconclusive reason is a note */
const BUG_ROWS = ['known-bug', 'known-bug-other-error', 'bug-fixed?'];
/** A reason in one table cell: one line, no `|` that would open a new column, at most 200 characters */
const cell = (s?: string) => String(s ?? '').replace(/\s*\r?\n\s*/g, ' ').replace(/\|/g, '\\|').slice(0, 200);
/** A known bug's row whose scenario is also @inconclusive: the inconclusive reason, as a note (@fail wins) */
const alsoInconclusive = (r: { outcome: string; reason?: string }) => (r.reason && BUG_ROWS.includes(r.outcome) ? ` (also @inconclusive: ${cell(r.reason)})` : '');

export default class SummaryReporter implements Reporter {
  private rows = new Map<string, Row>();
  private knownBugs = loadKnownBugs();
  private inconclusive = loadInconclusive();
  private setupErrors: string[] = [];
  private all: TestCase[] = [];
  /** Cleanups registered with ctx.onCleanup that failed (data left behind); they never fail a case. */
  private cleanupFailed = new Map<string, string>();
  private intermittent = new Map<string, { bug: string; caseId: string; example?: string; runs: number; failures: number }>();
  /** Errors outside any test (a global setup or teardown, a worker that crashed): Playwright's verdict stands with one. */
  private globalErrors: string[] = [];

  onError(error: { message?: string }): void {
    this.globalErrors.push(clean(error?.message) ?? 'error outside the tests');
  }

  onBegin(_config: FullConfig, suite: Suite): void {
    this.all = suite.allTests().filter((t) => t.parent.project()?.name !== 'setup');
  }

  /** Why a scenario tagged @inconclusive is so on web, or undefined: inconclusive on another platform only. With no entry the
   *  tag was written by hand: it still counts, with that said as its reason */
  private inconclusiveReason(test: TestCase): string | undefined {
    const entry = this.inconclusive[caseOf(test).id];
    if (!entry) return 'no entry in .qa-cluster/inconclusive.json (the tag was written by hand?)';
    return entry.platforms?.web ? (entry.platforms.web.reason ?? 'no reason recorded') : undefined;
  }

  onTestEnd(test: TestCase, result: TestResult): void {
    if (test.parent.project()?.name === 'setup') {
      if (result.status !== 'passed' && result.status !== 'skipped')
        this.setupErrors.push(`${test.title}: ${clean(result.error?.message) ?? result.status}`);
      return;
    }
    const annotations = [...test.annotations, ...((result as { annotations?: TestCase['annotations'] }).annotations ?? [])];
    const { id, title } = caseOf(test);
    // Known bugs: Gherkin tags `@fail @BUG-NNN` (playwright-bdd turns @fail into test.fail()); annotations as fallback
    // A scenario can carry several bugs (`@fail @BUG-002 @BUG-005`, most severe first): all are listed and any of their
    // signatures is accepted; it only counts as fixed when the scenario passes, i.e. all of them are fixed.
    const tagBugs = test.tags.filter((t) => /^@BUG-\d+$/.test(t)).map((t) => t.slice(1));
    const annBug = annotations.find((a) => a.type === 'fail' && /BUG-\d+/.test(a.description ?? ''))?.description?.match(/BUG-\d+/)?.[0];
    for (const a of annotations.filter((x) => x.type === 'cleanup-failed'))
      this.cleanupFailed.set(`${id}: ${a.description ?? ''}`, id);
    const isIntermittent = test.tags.includes('@intermittent');
    const bugIds = tagBugs.length ? tagBugs : annBug ? [annBug] : [];
    const bug = test.expectedStatus === 'failed' || isIntermittent ? (bugIds.length ? bugIds.join(', ') : 'BUG-?') : undefined;
    const testgraph = test.tags.find((t) => t.startsWith('@tg-'))?.slice(4) ?? annotations.find((a) => a.type === 'testgraph')?.description;
    const outcome = test.outcome();
    let status: string =
      outcome === 'flaky' ? 'flaky' : outcome === 'skipped' ? 'skipped' : outcome === 'expected' ? 'passed' : 'failed';
    let otherError: string | undefined;
    if (bug && outcome === 'expected') {
      status = 'known-bug';
      const sigs = bugIds.map((b) => this.knownBugs[b]?.signature).filter((x): x is string => !!x);
      const errors = (result.errors?.length ? result.errors : result.error ? [result.error] : [])
        .map((e) => (e.message ?? '').replace(/\x1b\[[0-9;]*m/g, ''));
      const isKnown = (m: string) => sigs.some((sig) => matches(sig, m));
      // Each known bug produces its own error; any other error in the same run is a new problem it would mask
      const others = sigs.length ? errors.filter((m) => !isKnown(m)) : [];
      if (sigs.length && (others.length || !errors.some(isKnown))) {
        status = 'known-bug-other-error';
        otherError = clean(others[0] ?? errors[0]) ?? 'failed without the known bug signature';
      }
    }
    if (bug && outcome === 'unexpected' && result.status === 'passed') status = 'bug-fixed?';
    if (isIntermittent) {
      if (outcome === 'skipped') status = 'known-intermittent';
      else {
        status = result.status === 'passed' ? 'intermittent-pass' : 'intermittent-fail';
        const key = `${bug}:${id} ${title}`;
        // an Outline's examples: one line each in the table, named by their example (review of fix/outline-case-id, 8)
        const example = /^Example #\d+$/.test(test.title) ? test.title : undefined;
        const agg = this.intermittent.get(key) ?? { bug: bug!, caseId: id, ...(example ? { example } : {}), runs: 0, failures: 0 };
        agg.runs += 1; if (status === 'intermittent-fail') agg.failures += 1;
        this.intermittent.set(key, agg);
      }
    }
    let reason: string | undefined;
    // flaky (failed, then passed on a retry): it passed, so it stays flaky and green (D1), with its reason
    if (test.tags.includes('@inconclusive') && !bug && ['failed', 'passed', 'flaky'].includes(status)) {
      reason = this.inconclusiveReason(test);
      if (reason && status !== 'flaky') status = status === 'failed' ? 'known-inconclusive' : 'inconclusive-passed';
    }
    // @fail wins over @inconclusive (a known bug failing as expected is not red), but the inconclusive is not lost: its
    // reason is a note on the bug's row, and `qa-cluster test` clears it with the bug when the scenario passes
    if (test.tags.includes('@inconclusive') && bug && BUG_ROWS.includes(status)) reason = this.inconclusiveReason(test);
    // A failure caused by another known bug (not tagged here): name it, keep the failure
    let knownMatch: string | undefined;
    if (status === 'failed' || status === 'known-bug-other-error') {
      const errs = (result.errors?.length ? result.errors : result.error ? [result.error] : []).map((e) => (e.message ?? '').replace(/\x1b\[[0-9;]*m/g, ''));
      const hits = Object.entries(this.knownBugs).filter(([bid, b]) => !bugIds.includes(bid) && b.signature && errs.some((m) => matches(b.signature!, m)));
      if (hits.length) knownMatch = hits.map(([bid, b]) => `${bid}${b.suspected ? ' (suspected)' : ''}${b.stage ? ` in the ${b.stage}` : ''}`).join(', ');
    }
    this.rows.set(test.id, {
      id, title, file: test.location.file.replace(process.cwd() + '/', ''),
      outcome: status, duration: result.duration, bug, testgraph, knownMatch, ...(reason ? { reason } : {}),
      error: status === 'failed' || status === 'known-inconclusive' ? clean(result.error?.message) : otherError,
    });
  }

  async onEnd(result: FullResult): Promise<{ status?: FullResult['status'] } | void> {
    for (const t of this.all) {
      if (this.rows.has(t.id)) continue;
      const { id, title } = caseOf(t);
      this.rows.set(t.id, { id, title, file: t.location.file.replace(process.cwd() + '/', ''),
        outcome: 'not-run', duration: 0, error: this.setupErrors.length ? 'setup failed' : 'did not run' });
    }
    const rows = [...this.rows.values()].sort((a, b) => a.id.localeCompare(b.id));
    const count = (s: string) => rows.filter((r) => r.outcome === s).length;
    const totals = { passed: count('passed'), failed: count('failed'), flaky: count('flaky'), knownBugs: count('known-bug'),
      bugFixed: count('bug-fixed?'), otherError: count('known-bug-other-error'), skipped: count('skipped'), notRun: count('not-run'),
      knownIntermittent: count('known-intermittent'), inconclusive: count('known-inconclusive'), inconclusivePassed: count('inconclusive-passed'), total: rows.length - count('intermittent-pass') - count('intermittent-fail'),
      setupErrors: this.setupErrors, globalErrors: this.globalErrors, status: result.status };
    const intermittent = [...this.intermittent.values()];
    // Failures of @intermittent scenarios are expected (they are known bugs): they do not make the run broken
    // A known bug's test that passed (bug-fixed?) is green: Playwright counts a passing @fail scenario as unexpected and fails
    // the run, so when that is the only thing it failed for — no failure, no other error, nothing left without running, no
    // setup or global error — the run is passed. Anything else red keeps its verdict.
    const onlyFixed = result.status === 'failed' && totals.bugFixed > 0 && !totals.failed && !totals.otherError && !totals.notRun && !totals.inconclusive
      && !this.setupErrors.length && !this.globalErrors.length && !intermittent.some((i) => i.failures);
    if (onlyFixed) totals.status = 'passed';
    const otherFailures = rows.some((r) => r.outcome === 'failed' || r.outcome === 'known-inconclusive') || (result.status !== 'passed' && !onlyFixed && !intermittent.some((i) => i.failures));
    const broken = totals.failed || totals.otherError || totals.notRun || this.setupErrors.length || otherFailures;
    const icon = broken ? '❌' : totals.flaky ? '⚠️' : '✅';
    const md = [
      totals.total === 0 && intermittent.length ? '## 🔁 E2E — known intermittent bugs check' : `## ${icon} E2E — ${totals.passed + totals.bugFixed}/${totals.total} OK`,
      '',
      '| Passed | Failed | Flaky | Known bugs | Known bug, other error | Known intermittent | Bug fixed | Not run | Skipped |',
      '|---|---|---|---|---|---|---|---|---|',
      `| ${totals.passed} | ${totals.failed} | ${totals.flaky} | ${totals.knownBugs} | ${totals.otherError} | ${totals.knownIntermittent} | ${totals.bugFixed} | ${totals.notRun} | ${totals.skipped} |`,
      ...(intermittent.length ? ['', '**Intermittent bugs (RUN_INTERMITTENT=1):**', '', '| Bug | Case | Failed | Hint |', '|---|---|---|---|',
        ...intermittent.map((i) => `| ${i.bug} | ${i.caseId}${i.example ? ` (${i.example})` : ''} | ${i.failures}/${i.runs} | ${i.failures === 0 && i.runs >= 4 ? 'bug-fixed? remove the tags' : 'still reproduces'} |`)] : []),
      '',
      ...(this.setupErrors.length ? ['**Setup failed** (login / storageState):', ...this.setupErrors.map((e) => `- ${e}`), ''] : []),
      ...(rows.some((r) => !['passed', 'intermittent-pass', 'intermittent-fail'].includes(r.outcome))
        ? ['| Case | Status | Detail |', '|---|---|---|',
           ...rows.filter((r) => !['passed', 'intermittent-pass', 'intermittent-fail'].includes(r.outcome))
             .map((r) => `| ${r.id} ${r.title} | ${r.outcome} | ${r.knownMatch ? `matches ${r.knownMatch}: ` : ''}${r.outcome === 'known-bug-other-error' ? `${r.bug}: ${r.error}`
               : r.outcome === 'known-inconclusive' ? `inconclusive: ${cell(r.reason)}${r.error ? ` — ${r.error}` : ''}`
               : r.outcome === 'inconclusive-passed' ? `passed: the @inconclusive tag can be removed (it was: ${cell(r.reason)})`
               : r.outcome === 'bug-fixed?' ? `${r.bug} fixed: its test passed in this run` : (r.bug ?? r.error ?? '')}${alsoInconclusive(r)} |`), '']
        : []),
      totals.bugFixed ? '> A known bug\'s test passed, so it is green: the bug is fixed in this run. `qa-cluster test` removes its `@fail @BUG-NNN` tags and closes it; by hand, remove the tags and its entry in `.qa-cluster/known-bugs.json`.' + (rows.some((r) => r.outcome === 'bug-fixed?' && r.reason) ? ' It was also @inconclusive: `qa-cluster test` clears that too; by hand, also remove `@inconclusive` and its entry in `.qa-cluster/inconclusive.json`.' : '') + '\n' : '',
      totals.otherError ? '> A known-bug scenario failed with a different error than its bug: that is a new failure the `@fail` tag would otherwise hide.\n' : '',
      totals.inconclusive ? '> An @inconclusive scenario is a case QACluster could not validate (the reason is in the table): it stays red until a person resolves it and removes the tag and its entry in `.qa-cluster/inconclusive.json`.\n' : '',
      rows.some((r) => r.knownMatch?.includes('precondition'))
        ? '> "matches BUG-NNN in the precondition": a known product bug broke the preparation of that case, so it never reached what it verifies. The failure is real (the bug is), but it says nothing about the feature the case checks.\n' : '',
      ...(this.cleanupFailed.size ? ['**Cleanups that failed** (data left behind; the cases themselves are not affected):', '',
        ...[...this.cleanupFailed.keys()].map((k) => `- ${k}`), ''] : []),
      'Full report: `e2e/playwright-report/index.html`',
    ].join('\n');
    mkdirSync('test-results', { recursive: true });
    writeFileSync('test-results/summary.md', md + '\n');
    writeFileSync('test-results/summary.json', JSON.stringify({ totals, intermittent, rows, cleanupFailed: [...this.cleanupFailed.keys()] }, null, 2));
    if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, md + '\n');
    // Playwright counts a @fail scenario that failed for another reason as "expected": make the run red ourselves
    if (totals.otherError && result.status === 'passed') return { status: 'failed' as const };
    if (onlyFixed) return { status: 'passed' as const };
  }

  printsToStdio(): boolean { return false; }
}
